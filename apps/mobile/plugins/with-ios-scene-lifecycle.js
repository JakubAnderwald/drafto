const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

/**
 * Expo config plugin that moves the iOS app onto the UIScene lifecycle
 * (ADR-0046).
 *
 * iOS 27 stops an app that is built with the iOS 27 SDK (Xcode 27) and has not
 * adopted scenes: UIKit traps in
 * `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption` while
 * creating the first scene, so the app crashes on every launch. Expo SDK 55's
 * AppDelegate template (and SDK 57's) still creates the window in
 * `didFinishLaunchingWithOptions`, the legacy lifecycle.
 *
 * The plugin:
 * - declares a single-window scene manifest in Info.plist;
 * - stops AppDelegate from creating the window and starting React Native, and
 *   keeps the launch options for the scene;
 * - adds SceneDelegate.swift, which creates the window, starts React Native,
 *   and forwards URLs and user activities to the AppDelegate callbacks that
 *   RCTLinkingManager and Expo's subscribers (expo-linking) listen on.
 *
 * The AppDelegate edits are anchored on Expo's generated template and throw when
 * an anchor is missing, so a template change fails `expo prebuild` instead of
 * shipping an app that crashes on launch. Remove this plugin once Expo's
 * template adopts scenes.
 */
const MARKER = "drafto: UIScene lifecycle";

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: "Default Configuration",
        UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
      },
    ],
  },
};

const FACTORY_PROPERTY_ANCHOR = "  var reactNativeFactory: RCTReactNativeFactory?\n";

// The block in `didFinishLaunchingWithOptions` that creates the window and starts
// React Native. Whitespace-tolerant, but every token must be present.
const WINDOW_BLOCK_ANCHOR =
  /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\(\s*withModuleName: "main",\s*in: window,\s*launchOptions: launchOptions\)\s*\n#endif\n/;

function setSceneManifest(infoPlist) {
  return { ...infoPlist, UIApplicationSceneManifest: SCENE_MANIFEST };
}

function patchAppDelegate(contents) {
  if (contents.includes(MARKER)) {
    return contents;
  }

  if (!contents.includes(FACTORY_PROPERTY_ANCHOR)) {
    throw new Error(
      "with-ios-scene-lifecycle: AppDelegate.swift no longer declares `var reactNativeFactory: RCTReactNativeFactory?`. " +
        "Expo's template changed; update the plugin before building, or the app will crash on iOS 27.",
    );
  }
  if (!WINDOW_BLOCK_ANCHOR.test(contents)) {
    throw new Error(
      'with-ios-scene-lifecycle: AppDelegate.swift no longer creates the window with `factory.startReactNative(withModuleName: "main", in: window, …)`. ' +
        "Expo's template changed; update the plugin before building, or the app will crash on iOS 27.",
    );
  }

  return contents
    .replace(
      FACTORY_PROPERTY_ANCHOR,
      `${FACTORY_PROPERTY_ANCHOR}  // ${MARKER}: SceneDelegate starts React Native with these.\n  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?\n`,
    )
    .replace(
      WINDOW_BLOCK_ANCHOR,
      `    // ${MARKER}: the window is created in SceneDelegate (iOS 27 requires scenes, ADR-0046).\n    self.launchOptions = launchOptions\n`,
    );
}

const SCENE_DELEGATE_SWIFT = `import React
import UIKit

// ${MARKER} — generated by plugins/with-ios-scene-lifecycle.js (ADR-0046).
//
// iOS 27 stops an app built with the iOS 27 SDK that has not adopted scenes, so
// the React Native window is created here instead of in AppDelegate. Under
// scenes iOS no longer calls the AppDelegate URL callbacks, so every URL and
// user activity is forwarded to them: RCTLinkingManager and expo-linking (which
// expo-router reads the launch URL from) still listen there.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate = appDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // A cold-start URL or universal link arrives here, not in launchOptions.
    // Put it where RCTLinkingManager's getInitialURL looks.
    var launchOptions = appDelegate.launchOptions ?? [:]
    let launchURL = connectionOptions.urlContexts.first
    if let context = launchURL {
      launchOptions[.url] = context.url
      if let source = context.options.sourceApplication {
        launchOptions[.sourceApplication] = source
      }
    }
    let launchActivity = connectionOptions.userActivities.first {
      $0.activityType == NSUserActivityTypeBrowsingWeb
    }
    if let activity = launchActivity {
      launchOptions[.userActivityDictionary] = [
        UIApplication.LaunchOptionsKey.userActivityType.rawValue: activity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": activity,
      ]
    }

    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)

    if let context = launchURL {
      forward(context)
    }
    if let activity = launchActivity {
      _ = appDelegate.application(UIApplication.shared, continue: activity) { _ in }
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      forward(context)
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = appDelegate?.application(UIApplication.shared, continue: userActivity) { _ in }
  }

  private func forward(_ context: UIOpenURLContext) {
    var options: [UIApplication.OpenURLOptionsKey: Any] = [
      .openInPlace: context.options.openInPlace
    ]
    if let source = context.options.sourceApplication {
      options[.sourceApplication] = source
    }
    if let annotation = context.options.annotation {
      options[.annotation] = annotation
    }
    _ = appDelegate?.application(UIApplication.shared, open: context.url, options: options)
  }
}
`;

function withIosSceneLifecycle(config) {
  config = withInfoPlist(config, (config) => {
    config.modResults = setSceneManifest(config.modResults);
    return config;
  });

  config = withAppDelegate(config, (config) => {
    if (config.modResults.language !== "swift") {
      throw new Error(
        `with-ios-scene-lifecycle: expected a Swift AppDelegate, got ${config.modResults.language}.`,
      );
    }
    config.modResults.contents = patchAppDelegate(config.modResults.contents);
    return config;
  });

  config = withDangerousMod(config, [
    "ios",
    (config) => {
      const { platformProjectRoot, projectName } = config.modRequest;
      fs.writeFileSync(
        path.join(platformProjectRoot, projectName, "SceneDelegate.swift"),
        SCENE_DELEGATE_SWIFT,
      );
      return config;
    },
  ]);

  config = withXcodeProject(config, (config) => {
    const { projectName } = config.modRequest;
    const filepath = `${projectName}/SceneDelegate.swift`;
    if (!config.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: config.modResults,
      });
    }
    return config;
  });

  return config;
}

module.exports = withIosSceneLifecycle;
module.exports.patchAppDelegate = patchAppDelegate;
module.exports.setSceneManifest = setSceneManifest;
module.exports.SCENE_DELEGATE_SWIFT = SCENE_DELEGATE_SWIFT;
module.exports.MARKER = MARKER;
